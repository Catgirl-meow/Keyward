// Email alias forwarders (same services as Bitwarden's generator).
export type ForwarderId = "simplelogin" | "addy" | "firefoxrelay" | "fastmail" | "duckduckgo" | "forwardemail";

export interface ForwarderConfig {
  token: string;
  domain?: string; // addy.io / forwardemail domain
  baseUrl?: string; // self-hosted SimpleLogin / addy
}

export const FORWARDERS: Record<ForwarderId, { name: string; needsDomain?: boolean; selfHost?: boolean; help: string }> = {
  simplelogin: { name: "SimpleLogin", selfHost: true, help: "API key from app.simplelogin.io → API Keys" },
  addy: { name: "addy.io", needsDomain: true, selfHost: true, help: "API token from app.addy.io → Settings → API" },
  firefoxrelay: { name: "Firefox Relay", help: "API key from relay.firefox.com → Settings" },
  fastmail: { name: "Fastmail", help: "API token with Masked Email scope" },
  duckduckgo: { name: "DuckDuckGo", help: "Email Protection token" },
  forwardemail: { name: "Forward Email", needsDomain: true, help: "API key from forwardemail.net → My Account → Security" },
};

async function json(r: Response) {
  if (!r.ok) throw new Error(`${r.status} ${(await r.text()).slice(0, 200)}`);
  return r.json();
}

export async function createAlias(id: ForwarderId, c: ForwarderConfig, site: string): Promise<string> {
  const desc = `Generated by Keyward${site ? ` for ${site}` : ""}`;
  switch (id) {
    case "simplelogin": {
      const base = (c.baseUrl || "https://app.simplelogin.io").replace(/\/+$/, "");
      const r = await json(await fetch(`${base}/api/alias/random/new${site ? `?hostname=${encodeURIComponent(site)}` : ""}`, {
        method: "POST", headers: { Authentication: c.token, "Content-Type": "application/json" }, body: JSON.stringify({ note: desc }),
      }));
      return r.alias;
    }
    case "addy": {
      const base = (c.baseUrl || "https://app.addy.io").replace(/\/+$/, "");
      const r = await json(await fetch(`${base}/api/v1/aliases`, {
        method: "POST",
        headers: { Authorization: `Bearer ${c.token}`, "Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest" },
        body: JSON.stringify({ domain: c.domain, description: desc }),
      }));
      return r.data.email;
    }
    case "firefoxrelay": {
      const r = await json(await fetch("https://relay.firefox.com/api/v1/relayaddresses/", {
        method: "POST", headers: { Authorization: `Token ${c.token}`, "Content-Type": "application/json" },
        body: JSON.stringify({ enabled: true, generated_for: site, description: desc }),
      }));
      return r.full_address;
    }
    case "duckduckgo": {
      const r = await json(await fetch("https://quack.duckduckgo.com/api/email/addresses", { method: "POST", headers: { Authorization: `Bearer ${c.token}` } }));
      return `${r.address}@duck.com`;
    }
    case "forwardemail": {
      const r = await json(await fetch(`https://api.forwardemail.net/v1/domains/${encodeURIComponent(c.domain ?? "")}/aliases`, {
        method: "POST",
        headers: { Authorization: "Basic " + btoa(`${c.token}:`), "Content-Type": "application/json" },
        body: JSON.stringify({ labels: site, description: desc }),
      }));
      return `${r.name}@${r.domain?.name ?? c.domain}`;
    }
    case "fastmail": {
      const sess = await json(await fetch("https://api.fastmail.com/jmap/session", { headers: { Authorization: `Bearer ${c.token}` } }));
      const accountId = sess.primaryAccounts?.["https://www.fastmail.com/dev/maskedemail"];
      const r = await json(await fetch("https://api.fastmail.com/jmap/api/", {
        method: "POST",
        headers: { Authorization: `Bearer ${c.token}`, "Content-Type": "application/json" },
        body: JSON.stringify({
          using: ["urn:ietf:params:jmap:core", "https://www.fastmail.com/dev/maskedemail"],
          methodCalls: [["MaskedEmail/set", { accountId, create: { kw: { state: "enabled", description: desc, forDomain: site, emailPrefix: "" } } }, "0"]],
        }),
      }));
      const created = r.methodResponses?.[0]?.[1]?.created?.kw;
      if (!created?.email) throw new Error("Fastmail did not create an alias");
      return created.email;
    }
  }
}
