// Precomputes Keyguard-style accent palettes (Material 500 swatches → SchemeVibrant accent
// roles). Surfaces stay neutral, exactly like Keyguard's "plain" scheme.
// Run: node scripts/gen-theme.ts  → src/ui/theme/palettes.gen.ts
import { argbFromHex, hexFromArgb, Hct, MaterialDynamicColors as C, SchemeVibrant } from "@material/material-color-utilities";
import { writeFileSync } from "node:fs";

const SWATCHES: [id: string, label: string, hex: string][] = [
  ["red", "Red", "#F44336"], ["pink", "Pink", "#E91E63"], ["purple", "Purple", "#9C27B0"], ["deep-purple", "Deep purple", "#673AB7"],
  ["indigo", "Indigo", "#3F51B5"], ["blue", "Blue", "#2196F3"], ["cyan", "Cyan", "#0097A7"], ["teal", "Teal", "#009688"],
  ["green", "Green", "#43A047"], ["light-green", "Light green", "#8BC34A"], ["lime", "Lime", "#CDDC39"], ["yellow", "Yellow", "#FFEB3B"],
  ["amber", "Amber", "#FFC107"], ["orange", "Orange", "#FF9800"], ["deep-orange", "Deep orange", "#FF5722"], ["brown", "Brown", "#795548"],
  ["gray", "Gray", "#888888"],
];

const ROLES = [
  "primary", "onPrimary", "primaryContainer", "onPrimaryContainer", "inversePrimary",
  "secondary", "onSecondary", "secondaryContainer", "onSecondaryContainer",
  "tertiary", "onTertiary", "tertiaryContainer", "onTertiaryContainer",
  "outline", "outlineVariant", "surfaceVariant", "onSurfaceVariant", "inverseSurface", "inverseOnSurface",
] as const;

const kebab = (s: string) => s.replace(/[A-Z]/g, (m) => "-" + m.toLowerCase());

const out: Record<string, { label: string; seed: string; light: Record<string, string>; dark: Record<string, string> }> = {};
for (const [id, label, hex] of SWATCHES) {
  const entry = { label, seed: hex, light: {} as Record<string, string>, dark: {} as Record<string, string> };
  for (const dark of [false, true]) {
    const scheme = new SchemeVibrant(Hct.fromInt(argbFromHex(hex)), dark, 0);
    for (const r of ROLES) (dark ? entry.dark : entry.light)[kebab(r)] = hexFromArgb((C as any)[r].getArgb(scheme));
  }
  out[id] = entry;
}

// Compose M3 baseline (used when "Default" accent is selected) — Keyguard's fallback.
out["default"] = {
  label: "Default",
  seed: "#6750A4",
  light: {
    primary: "#6750A4", "on-primary": "#FFFFFF", "primary-container": "#EADDFF", "on-primary-container": "#21005D", "inverse-primary": "#D0BCFF",
    secondary: "#625B71", "on-secondary": "#FFFFFF", "secondary-container": "#E8DEF8", "on-secondary-container": "#1D192B",
    tertiary: "#7D5260", "on-tertiary": "#FFFFFF", "tertiary-container": "#FFD8E4", "on-tertiary-container": "#31111D",
    outline: "#79747E", "outline-variant": "#CAC4D0", "surface-variant": "#E7E0EC", "on-surface-variant": "#49454F",
    "inverse-surface": "#313033", "inverse-on-surface": "#F4EFF4",
  },
  dark: {
    primary: "#D0BCFF", "on-primary": "#381E72", "primary-container": "#4F378B", "on-primary-container": "#EADDFF", "inverse-primary": "#6750A4",
    secondary: "#CCC2DC", "on-secondary": "#332D41", "secondary-container": "#4A4458", "on-secondary-container": "#E8DEF8",
    tertiary: "#EFB8C8", "on-tertiary": "#492532", "tertiary-container": "#633B48", "on-tertiary-container": "#FFD8E4",
    outline: "#938F99", "outline-variant": "#49454F", "surface-variant": "#49454F", "on-surface-variant": "#CAC4D0",
    "inverse-surface": "#E6E1E5", "inverse-on-surface": "#313033",
  },
};

const ts = `// Generated by scripts/gen-theme.ts — do not edit.\nexport const PALETTES: Record<string, { label: string; seed: string; light: Record<string, string>; dark: Record<string, string> }> = ${JSON.stringify(out, null, 1)};\n`;
writeFileSync(process.cwd() + "/src/ui/theme/palettes.gen.ts", ts);
console.log("palettes:", Object.keys(out).length);
