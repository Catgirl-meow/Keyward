// Each forwarder's request (URL, method, auth header, body) and how its answer is read.
import { afterEach, describe, expect, test, vi } from "vitest";
import { checkServerUrl, createAlias, type ForwarderId } from "../../src/core/generator/forwarders.ts";

interface Seen { url: string; method: string; headers: Record<string, string>; body: any }
function stub(answers: unknown[]): Seen[] {
  const seen: Seen[] = [];
  vi.stubGlobal("fetch", async (url: string, init: RequestInit = {}) => {
    seen.push({ url, method: init.method ?? "GET", headers: Object.fromEntries(Object.entries(init.headers ?? {})), body: init.body ? JSON.parse(String(init.body)) : null });
    return new Response(JSON.stringify(answers.shift()), { status: 200, headers: { "content-type": "application/json" } });
  });
  return seen;
}
afterEach(() => vi.unstubAllGlobals());

const desc = "Generated by Keyward for shop.example";
const CASES: [ForwarderId, { token: string; domain?: string; baseUrl?: string }, unknown[], string, Partial<Seen>[]][] = [
  ["simplelogin", { token: "sl-key" }, [{ alias: "shop.x7@simplelogin.com" }], "shop.x7@simplelogin.com",
    [{ url: "https://app.simplelogin.io/api/alias/random/new?hostname=shop.example", method: "POST", headers: { Authentication: "sl-key", "Content-Type": "application/json" }, body: { note: desc } }]],
  ["simplelogin", { token: "sl-key", baseUrl: "https://sl.home.example/" }, [{ alias: "a@sl.home.example" }], "a@sl.home.example",
    [{ url: "https://sl.home.example/api/alias/random/new?hostname=shop.example" }]],
  ["addy", { token: "addy-key", domain: "kay.anonaddy.me" }, [{ data: { email: "x1@kay.anonaddy.me" } }], "x1@kay.anonaddy.me",
    [{ url: "https://app.addy.io/api/v1/aliases", method: "POST", headers: { Authorization: "Bearer addy-key", "Content-Type": "application/json", "X-Requested-With": "XMLHttpRequest" }, body: { domain: "kay.anonaddy.me", description: desc } }]],
  ["firefoxrelay", { token: "relay-key" }, [{ full_address: "abc@mozmail.com" }], "abc@mozmail.com",
    [{ url: "https://relay.firefox.com/api/v1/relayaddresses/", method: "POST", headers: { Authorization: "Token relay-key", "Content-Type": "application/json" }, body: { enabled: true, generated_for: "shop.example", description: desc } }]],
  ["duckduckgo", { token: "ddg-key" }, [{ address: "quiet-fox" }], "quiet-fox@duck.com",
    [{ url: "https://quack.duckduckgo.com/api/email/addresses", method: "POST", headers: { Authorization: "Bearer ddg-key" } }]],
  ["forwardemail", { token: "fe-key", domain: "kay.example" }, [{ name: "shop1", domain: { name: "kay.example" } }], "shop1@kay.example",
    [{ url: "https://api.forwardemail.net/v1/domains/kay.example/aliases", method: "POST", headers: { Authorization: "Basic " + btoa("fe-key:"), "Content-Type": "application/json" }, body: { labels: "shop.example", description: desc } }]],
  ["fastmail", { token: "fm-key" }, [
    { primaryAccounts: { "https://www.fastmail.com/dev/maskedemail": "acc1" } },
    { methodResponses: [["MaskedEmail/set", { created: { kw: { email: "masked.1@fastmail.com" } } }, "0"]] },
  ], "masked.1@fastmail.com", [
    { url: "https://api.fastmail.com/jmap/session", method: "GET", headers: { Authorization: "Bearer fm-key" } },
    { url: "https://api.fastmail.com/jmap/api/", method: "POST", body: {
      using: ["urn:ietf:params:jmap:core", "https://www.fastmail.com/dev/maskedemail"],
      methodCalls: [["MaskedEmail/set", { accountId: "acc1", create: { kw: { state: "enabled", description: desc, forDomain: "shop.example", emailPrefix: "" } } }, "0"]],
    } },
  ]],
];

describe("forwarders", () => {
  test.each(CASES)("%s", async (id, cfg, answers, alias, want) => {
    const seen = stub(answers);
    expect(await createAlias(id, cfg, "shop.example")).toBe(alias);
    expect(seen).toHaveLength(want.length);
    want.forEach((w, i) => expect(seen[i]).toMatchObject(w));
  });

  test("an error answer becomes an error with the status", async () => {
    vi.stubGlobal("fetch", async () => new Response("bad token", { status: 401 }));
    await expect(createAlias("duckduckgo", { token: "x" }, "")).rejects.toThrow("401 bad token");
  });

  test("a self-hosted server URL must be https, or http to this machine", () => {
    expect(checkServerUrl("https://sl.example.org/")).toBe("https://sl.example.org");
    expect(checkServerUrl("https://h.example/sub/path/")).toBe("https://h.example/sub/path");
    expect(checkServerUrl("http://localhost:7000")).toBe("http://localhost:7000");
    expect(checkServerUrl("http://sl.example.org")).toBeNull();
    expect(checkServerUrl("javascript:alert(1)")).toBeNull();
    expect(checkServerUrl("not a url")).toBeNull();
  });
});
